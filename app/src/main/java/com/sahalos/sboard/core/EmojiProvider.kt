            flags.forEach { (emoji, tags) -> add(EmojiItem(emoji, EmojiCategory.FLAGS, tags)) }
        }
    }

    fun getEmojisForCategory(category: EmojiCategory): List<String> {
        return allEmojis.filter { it.category == category }.map { it.emoji }
    }

    fun search(query: String): List<String> {
        val trimmed = query.trim().lowercase()
        if (trimmed.isEmpty()) return emptyList()

        return allEmojis.filter { item ->
            item.emoji == trimmed || item.tags.contains(trimmed)
        }.map { it.emoji }.distinct()
    }
}
